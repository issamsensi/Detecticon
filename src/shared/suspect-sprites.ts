export type Gender = 'm' | 'f';

export const getSuspectFirstName = (name: string): string =>
  name.trim().split(/\s+/)[0] ?? '';

export const getSuspectGender = (name: string): Gender | undefined =>
  SUSPECT_GENDERS[getSuspectFirstName(name)];

/** Stable pool order; the client indexes it by puzzle id + suspect index. */
export const getSpriteKeysForGender = (gender: Gender): string[] =>
  Object.keys(SUSPECT_SPRITE_GENDERS).filter(
    (key) => SUSPECT_SPRITE_GENDERS[key] === gender
  );
